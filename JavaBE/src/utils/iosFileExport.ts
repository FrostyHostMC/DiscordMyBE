import { createZipArchive, type ZipEntry } from '@/utils/zip';
import { preparePackForExport } from '@/utils/packIntegrity';
import type { BedrockRemake } from '@/types/remaker';

export interface ExportResult {
  success: boolean;
  message: string;
}

function packEntries(files: Record<string, string | Uint8Array>): ZipEntry[] {
  return Object.entries(files).map(([path, data]) => ({ path, data }));
}

function asArrayBuffer(bytes: Uint8Array): ArrayBuffer {
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
}

export async function exportToIosFiles(remake: BedrockRemake): Promise<ExportResult> {
  // Same import gate as the main export path, so a pack that would be rejected by
  // Bedrock is never handed to the share sheet.
  const behaviorPrep = preparePackForExport(remake.behaviorPackFiles, 'behavior');
  const resourcePrep = preparePackForExport(remake.resourcePackFiles, 'resources');
  const behaviorPack = createZipArchive(packEntries(behaviorPrep.files));
  const resourcePack = createZipArchive(packEntries(resourcePrep.files));
  const readme = [
    `${remake.name} — Bedrock Addon Draft Package`,
    `====================================================`,
    `Generated by Mod AI Remaker`,
    ``,
    `Pack Contents:`,
    `- Behavior Pack: ${remake.id}_behavior.mcpack`,
    `- Resource Pack: ${remake.id}_resources.mcpack`,
    `- Pack Icon: Extracted from archive when available; otherwise generated`,
    ``,
    `How to install on iOS:`,
    `1. Tap "Save to Files" in the iOS Share Sheet, or tap the Minecraft icon directly.`,
    `2. Open the .mcaddon file inside the iOS Files app; Minecraft Bedrock will open and import both packs automatically!`,
    `3. In your world settings:`,
    `   - Activate "${remake.name} (Behavior)" under Behavior Packs`,
    `   - Activate "${remake.name} (Resources)" under Resource Packs`,
    `   - Enable "Beta APIs" in Experiments for combat script execution.`,
  ].join('\n');

  const archive = createZipArchive([
    { path: `${remake.id}_behavior.mcpack`, data: behaviorPack },
    { path: `${remake.id}_resources.mcpack`, data: resourcePack },
    { path: 'README.txt', data: readme },
  ]);
  const blob = new Blob([asArrayBuffer(archive)], { type: 'application/octet-stream' });

  const share = navigator as Navigator & {
    canShare?: (data: { files?: File[] }) => boolean;
    share?: (data: { files?: File[]; title?: string; text?: string }) => Promise<void>;
  };

  if (share.canShare && share.share) {
    const file = new File([blob], remake.fileName, { type: 'application/octet-stream' });
    if (share.canShare({ files: [file] })) {
      try {
        await share.share({
          files: [file],
          title: `${remake.name} (Bedrock Addon)`,
          text: 'Save the Bedrock addon draft to iOS Files or open it in Minecraft.',
        });
        return { success: true, message: 'Share menu opened. Select Save to Files or tap Minecraft.' };
      } catch (error) {
        if (error instanceof Error && error.name === 'AbortError') {
          return { success: false, message: 'Share action was cancelled.' };
        }
        throw error;
      }
    }
  }

  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = remake.fileName;
  link.rel = 'noopener';
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 120000);
  return { success: true, message: 'Addon downloaded. Open the .mcaddon in Files to import to Minecraft!' };
}

